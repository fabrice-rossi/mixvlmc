test_that("misspelled arguments are reported (VLMC)", {
  withr::local_seed(0)
  x <- sample(c("A", "B", "C"), 200, replace = TRUE)
  y <- sample(c("A", "B", "C"), 50, replace = TRUE)
  for (backend in c("R", "C++")) {
    ct <- ctx_tree(x, backend = backend)
    expect_error(ctx_tree(x, keep_positon = FALSE, backend = backend), class = "rlib_error_dots_nonempty")
    expect_error(contexts(ct, type = "data.frame"), class = "rlib_error_dots_nonempty")
    expect_error(find_sequence(ct, "A", revrse = TRUE), class = "rlib_error_dots_nonempty")
    expect_error(as_vlmc(ct, alfa = 0.1), class = "rlib_error_dots_nonempty")
    expect_error(summary(ct, foo = 1), class = "rlib_error_dots_nonempty")
    m <- vlmc(x, backend = backend)
    expect_error(loglikelihood(m, new_data = y), class = "rlib_error_dots_nonempty")
    expect_error(logLik(m, newdata = y), class = "rlib_error_dots_nonempty")
    expect_error(simulate(m, 5, burn_in = 100), class = "rlib_error_dots_nonempty")
    expect_error(predict(m, y, final_prediction = TRUE), class = "rlib_error_dots_nonempty")
    expect_error(prune(m, verbose = TRUE), class = "rlib_error_dots_nonempty")
    expect_error(cutoff(m, sclae = "native"), class = "rlib_error_dots_nonempty")
    expect_error(metrics(m, newdata = y), class = "rlib_error_dots_nonempty")
    expect_error(contexts(m, with_metrics = TRUE), class = "rlib_error_dots_nonempty")
    expect_error(summary(m, foo = 1), class = "rlib_error_dots_nonempty")
    expect_error(trim(m, keep_model = TRUE), class = "rlib_error_dots_nonempty")
    m_tune <- tune_vlmc(x, backend = backend)
    expect_error(as_vlmc(m_tune, alpha = 0.1), class = "rlib_error_dots_nonempty")
    expect_error(summary(m_tune, foo = 1), class = "rlib_error_dots_nonempty")
  }
})

test_that("misspelled arguments are reported (COVLMC)", {
  pc <- powerconsumption[powerconsumption$week == 5, ]
  elec <- cut(pc$active_power, breaks = c(0, 0.4, 2, 8), labels = c("low", "typical", "high"))
  elec_cov <- data.frame(day = (pc$hour >= 7 & pc$hour <= 17))
  m <- covlmc(elec, elec_cov, min_size = 5)
  expect_error(loglikelihood(m, newdata = elec, newcovariate = elec_cov), class = "rlib_error_dots_nonempty")
  expect_error(simulate(m, 5, covariates = elec_cov), class = "rlib_error_dots_nonempty")
  expect_error(predict(m, elec, newcovariate = elec_cov), class = "rlib_error_dots_nonempty")
  expect_error(prune(m, cut_off = 1), class = "rlib_error_dots_nonempty")
  expect_error(contexts(m, hsizes = TRUE), class = "rlib_error_dots_nonempty")
  expect_error(metrics(m, foo = 1), class = "rlib_error_dots_nonempty")
  expect_error(trim(m, keep_models = TRUE), class = "rlib_error_dots_nonempty")
  expect_error(summary(m, foo = 1), class = "rlib_error_dots_nonempty")
})
